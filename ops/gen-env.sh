#!/usr/bin/env bash
# Writes ops/.env with freshly generated secrets for this host. Refuses to
# overwrite an existing file: the Postgres password is baked into the data
# volume on first boot, and the webhook key encrypts stored secrets, so
# rotating either silently would lock you out of existing data.
#
# Usage: ops/gen-env.sh [public-base-url]
#   e.g. ops/gen-env.sh https://filspay.example.dilmune.cloud
set -euo pipefail

ENV_FILE="$(cd "$(dirname "$0")" && pwd)/.env"
if [ -e "$ENV_FILE" ]; then
  echo "gen-env: $ENV_FILE already exists, not overwriting" >&2
  exit 1
fi

PUBLIC_BASE_URL="${1:-http://localhost:8080}"
case "$PUBLIC_BASE_URL" in
  https://*) COOKIE_SECURE=true ;;
  *) COOKIE_SECURE=false ;;
esac

umask 077
cat >"$ENV_FILE" <<EOF
# Generated by ops/gen-env.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Do not commit.
POSTGRES_PASSWORD=$(openssl rand -hex 24)
SETTLEMENT_INTERNAL_TOKEN=$(openssl rand -hex 32)
WEBHOOK_SECRET_ENCRYPTION_KEY=$(openssl rand -base64 32)
ACQUIRER_CALLBACK_SIGNING_SECRET=acqsec_$(openssl rand -hex 24)
PUBLIC_BASE_URL=$PUBLIC_BASE_URL
COOKIE_SECURE=$COOKIE_SECURE
PUBLIC_PORT=8080
# Demo only: shows the OTP on the login page (no email provider is wired).
OTP_DEV_EXPOSE=true
EOF
echo "gen-env: wrote $ENV_FILE (PUBLIC_BASE_URL=$PUBLIC_BASE_URL, COOKIE_SECURE=$COOKIE_SECURE)"
